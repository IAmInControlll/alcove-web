import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const appRepo = resolve(process.argv[2] ?? '../alcove');
const css = readFileSync(resolve(appRepo, 'src/app.css'), 'utf8');

const rootStart = css.indexOf(':root {');
const rootBody = css.slice(rootStart + ':root {'.length, css.indexOf('\n}', rootStart));
const rootVars = rootBody
  .split('\n')
  .filter((line) => /^\s*--[\w-]+\s*:/.test(line))
  .join('\n');

const blocks = [...css.matchAll(/^(\.theme-[\w-]+)([^{]*)\{([\s\S]*?)^\}/gm)].map(([, theme, rest, body]) => {
  const selector = `.alc-app${theme}${rest.trimEnd()}`;
  return `${selector} {${body}}`;
});

const out = [
  '/* Generated by scripts/sync-app-themes.mjs from the app repo. Do not edit by hand. */',
  '',
  `.alc-app {\n${rootVars}\n}`,
  '',
  blocks.join('\n\n'),
  '',
].join('\n');

writeFileSync(resolve('src/styles/app-themes.css'), out);
console.log(`wrote ${blocks.length} theme rules`);
